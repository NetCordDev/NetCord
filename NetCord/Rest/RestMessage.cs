using NetCord.JsonModels;

namespace NetCord.Rest;

/// <summary>
/// Represents a message sent in a channel within Discord.
/// </summary>
public partial class RestMessage(JsonMessage jsonModel, RestClient client) : ClientEntity(client)
{
    /// <summary>
    /// The ID of the message.
    /// </summary>
    public override ulong Id { get; } = jsonModel.Id;

    /// <summary>
    /// The ID of the channel the message was sent in.
    /// </summary>
    public ulong ChannelId { get; } = jsonModel.ChannelId;

    /// <summary>
    /// The <see cref="User"/> object of the message's author.
    /// </summary>
    /// <remarks>
    /// If the message is generated by a <see cref="Webhook"/>, the <see cref="User"/> object will correspond to the webhook's ID, username, and avatar.
    /// </remarks>
    public User Author { get; } = CreateAuthor(jsonModel, client);

    private static User CreateAuthor(JsonMessage jsonModel, RestClient client)
    {
        if (jsonModel.GuildUser is { } guildUser)
        {
            guildUser.User = jsonModel.Author;

            return new GuildUser(guildUser, jsonModel.GuildId.GetValueOrDefault(), client);
        }

        return new(jsonModel.Author!, client);
    }

    /// <summary>
    /// The text contents of the message.
    /// </summary>
    public string Content { get; } = jsonModel.Content;

    /// <summary>
    /// If the message has been edited, contains the timestamp of the latest edit, otherwise <see langword="null"/>.
    /// </summary>
    public DateTimeOffset? EditedAt { get; } = jsonModel.EditedAt;

    /// <summary>
    /// Whether the message was a Text-To-Speech message.
    /// </summary>
    public bool IsTts { get; } = jsonModel.IsTts;

    /// <summary>
    /// Whether the message mentions <see langword="@everyone"/>.
    /// </summary>
    public bool MentionsEveryone { get; } = jsonModel.MentionsEveryone;

    /// <summary>
    /// A list of users specifically mentioned in the message.
    /// </summary>
    public IReadOnlyList<User> MentionedUsers { get; } = CreateMentionedUsers(jsonModel, client);

    private static IReadOnlyList<User> CreateMentionedUsers(JsonMessage jsonModel, RestClient client)
    {
        var guildId = jsonModel.GuildId.GetValueOrDefault();

        return [.. jsonModel.MentionedUsers.Select(u =>
        {
            if (u.GuildUser is { } guildUser)
            {
                guildUser.User = u;
                return new GuildUser(guildUser, guildId, client);
            }

            return new User(u, client);
        })];
    }

    /// <summary>
    /// A list of IDs corresponding to roles specifically mentioned in the message.
    /// </summary>
    public IReadOnlyList<ulong> MentionedRoleIds { get; } = jsonModel.MentionedRoleIds;

    /// <summary>
    /// A list of <see cref="GuildChannelMention"/> objects indexed by their IDs, containing channels specifically mentioned in the message.
    /// </summary>
    /// <remarks>
    /// <para>This list is only populated for messages with the <see cref="MessageFlags.Crossposted"/> flag set.</para>
    /// <para>Only text channels visible to everyone in a lurkable guild will ever be included.</para>
    /// </remarks>
    public IReadOnlyList<GuildChannelMention> MentionedChannels { get; } = [.. jsonModel.MentionedChannels.SelectOrEmpty(c => new GuildChannelMention(c))];

    /// <summary>
    /// A list containing the message's attachments.
    /// </summary>
    public IReadOnlyList<Attachment> Attachments { get; } = [.. jsonModel.Attachments.Select(a => Attachment.Create(a, client))];

    /// <summary>
    /// A list of <see cref="Embed"/> objects, representing any embedded content present in the message.
    /// </summary>
    public IReadOnlyList<Embed> Embeds { get; } = [.. jsonModel.Embeds.Select(e => new Embed(e))];

    /// <summary>
    /// A list of <see cref="MessageReaction"/> objects, representing all reactions to the message.
    /// </summary>
    public IReadOnlyList<MessageReaction>? Reactions { get; } = jsonModel.Reactions?.Select(r => new MessageReaction(r)).ToArray();

    /// <summary>
    /// Used for validating that a message was sent.
    /// </summary>
    public string? Nonce { get; } = jsonModel.Nonce;

    /// <summary>
    /// Whether this message is pinned in a channel.
    /// </summary>
    public bool IsPinned { get; } = jsonModel.IsPinned;

    /// <summary>
    /// If the message was generated by a <see cref="Webhook"/>, contains the webhook's ID, otherwise <see langword="null"/>.
    /// </summary>
    public ulong? WebhookId { get; } = jsonModel.WebhookId;

    /// <summary>
    /// The type of the message.
    /// </summary>
    public MessageType Type { get; } = jsonModel.Type;

    /// <summary>
    /// Sent with Rich Presence-related chat embeds.
    /// </summary>
    public MessageActivity? Activity { get; } = jsonModel.Activity is { } activity ? new(activity) : null;

    /// <summary>
    /// Sent with Rich Presence-related chat embeds.
    /// </summary>
    public PartialApplication? Application { get; } = jsonModel.Application is { } application ? new(application, client) : null;

    /// <summary>
    /// If the message is an <see cref="NetCord.Interaction"/> response/followup or an application-owned <see cref="Webhook"/>, the ID of the <see cref="NetCord.Application"/>.
    /// </summary>
    public ulong? ApplicationId { get; } = jsonModel.ApplicationId;

    /// <summary>
    /// A <see cref="MessageFlags"/> object indicating the message's applied flags.
    /// </summary>
    public MessageFlags Flags { get; } = jsonModel.Flags.GetValueOrDefault();

    /// <summary>
    /// Contains data showing the source of a crosspost, channel follow add, pin, or message reply.
    /// </summary>
    public MessageReference? MessageReference { get; } = jsonModel.MessageReference is { } messageReference ? new(messageReference) : null;

    /// <summary>
    /// A list of messages associated with the message reference.
    /// </summary>
    public IReadOnlyList<MessageSnapshot>? MessageSnapshots { get; } = CreateMessageSnapshots(jsonModel, client);

    private static IReadOnlyList<MessageSnapshot>? CreateMessageSnapshots(JsonMessage jsonModel, RestClient client)
    {
        if (jsonModel.MessageReference is not { } messageReference)
            return null;

        var guildId = messageReference.GuildId;

        return jsonModel.MessageSnapshots?.Select(s => new MessageSnapshot(s, guildId, client)).ToArray();
    }

    /// <summary>
    /// The message associated with the <see cref="MessageReference"/>.
    /// </summary>
    /// <remarks>
    /// This field is only returned for messages with a <see cref="MessageType"/> of <see cref="MessageType.Reply"/> or <see cref="MessageType.ThreadStarterMessage"/>. If the message is a reply but the <see cref="ReferencedMessage"/> field is not present, the backend did not attempt to fetch the message that was being replied to, so its state is unknown. If the field exists but is null, the referenced message was deleted.
    /// </remarks>
    public RestMessage? ReferencedMessage { get; } = jsonModel.ReferencedMessage is { } referencedMessage ? new(referencedMessage, client) : null;

    /// <summary>
    /// Sent if the message is sent as a result of an interaction.
    /// </summary>
    public MessageInteractionMetadata? InteractionMetadata { get; } = jsonModel.InteractionMetadata is { } interactionMetadata ? new(interactionMetadata, client) : null;

    /// <summary>
    /// Sent if the message is a response to an interaction.
    /// </summary>
    [Obsolete($"Replaced by '{nameof(InteractionMetadata)}'")]
    public MessageInteraction? Interaction { get; } = jsonModel.Interaction is { } interaction ? new(interaction, jsonModel.GuildId, client) : null;

    /// <summary>
    /// The <see cref="GuildThread"/> that was started from this message, if any.
    /// </summary>
    public GuildThread? StartedThread { get; } = jsonModel.StartedThread is { } startedThread ? GuildThread.CreateFromJson(startedThread, client) : null;

    /// <summary>
    /// A list of <see cref="IMessageChildComponent"/> objects, contains components like <see cref="ButtonComponent"/>s, <see cref="ActionRowComponent"/>s, or other interactive components if any are present.
    /// </summary>
    public IReadOnlyList<IMessageChildComponent> Components { get; } = jsonModel.Components is { } components ? [.. components.Select(IMessageChildComponent.CreateFromJson)] : [];

    /// <summary>
    /// A list of stickers sent within the message.
    /// </summary>
    public IReadOnlyList<MessageSticker> Stickers { get; } = jsonModel.Stickers is { } stickers ? [.. stickers.Select(s => new MessageSticker(s, client))] : [];

    /// <summary>
    /// A generally increasing integer (there may be gaps or duplicates) that represents the approximate position of the message in a <see cref="GuildThread"/>.
    /// </summary>
    /// <remarks>
    /// It can be used to estimate the relative position of the message in a thread in tandem with the <see cref="GuildThread.TotalMessageSent"/> property of the parent thread.
    /// </remarks>
    public int? Position { get; } = jsonModel.Position;

    /// <summary>
    /// Contains information about the role subscription purchase or renewal that prompted this <see cref="MessageType.RoleSubscriptionPurchase"/> message.
    /// </summary>
    public RoleSubscriptionData? RoleSubscriptionData { get; } = jsonModel.RoleSubscriptionData is { } roleSubscriptionData ? new(roleSubscriptionData) : null;

    /// <summary>
    /// Contains information about the <see cref="User"/>, <see cref="GuildUser"/>, <see cref="IGuildChannel"/>, and <see cref="Role"/> objects in the message's auto-populated selection menus.
    /// </summary>
    public InteractionResolvedData? Resolved { get; } = jsonModel.Resolved is { } resolved ? new(resolved, jsonModel.GuildId, client) : null;

    /// <summary>
    /// The message's contained poll, if it has one, otherwise <see langword="null"/>.
    /// </summary>
    /// <remarks>
    /// This is always <see langword="null"/> if the <see cref="Gateway.GatewayIntents.MessageContent"/> intent is not set.
    /// </remarks>
    public MessagePoll? Poll { get; } = jsonModel.Poll is { } poll ? new(poll) : null;

    /// <summary>
    /// The call associated with the message, if any.
    /// </summary>
    public MessageCall? Call { get; } = jsonModel.Call is { } call ? new(call) : null;

    /// <summary>
    /// The custom client-side theme shared in the message, if any.
    /// </summary>
    public SharedClientTheme? SharedClientTheme { get; } = jsonModel.SharedClientTheme is { } sharedClientTheme ? new(sharedClientTheme) : null;

    /// <summary>
    /// Replies to the message, returning the resulting reply.
    /// </summary>
    /// <param name="replyMessage">The message to reply with.</param>
    /// <param name="properties">Optional properties to customize the request, can be <see langword="null"/>.</param>
    /// <param name="cancellationToken">A token that can be used to cancel the operation before it completes.</param>
    public Task<RestMessage> ReplyAsync(ReplyMessageProperties replyMessage, RestRequestProperties? properties = null, CancellationToken cancellationToken = default)
        => SendAsync(replyMessage.ToMessageProperties(Id), properties, cancellationToken);
}
